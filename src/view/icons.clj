(defn icon
  "Render a SVG icon by name.

   Options:
   - :size - :xs, :sm, :md, :lg (default :md)
   - :class - extra CSS classes"
  [name & {:keys [size class] :or {size :md}}]
  (let [size-c (case size
                 :xs "w-4 h-4"
                 :sm "w-5 h-5"
                 :md "w-6 h-6"
                 :lg "w-8 h-8"
                 "w-6 h-6")]
    [:svg {:class (merge-classes "text-current" size-c class)
           :fill "none"
           :stroke "currentColor"
           :viewBox "0 0 24 24"}
     [:path {:stroke-linecap "round"
             :stroke-linejoin "round"
             :stroke-width "2"
             :d (get icon-paths name)}]]))

(defn user-menu
  "Render user menu for header.

   Options:
   - :user - user map with :user/name and :user/avatar
   - :class - extra CSS classes"
  [{:keys [user class]}]
  [:div {:class (merge-classes "flex items-center space-x-3" class)}
   [:img {:src (or (:user/avatar user) "/static/img/avatar-default.svg")
          :alt (:user/name user)
          :class "w-8 h-8 rounded-full"}]
   [:span.hidden.md:block.text-sm.font-medium.text-gray-700 (:user/name user)]
   (icon :chevron-down {:size :sm :class "text-gray-400"})])